#!/usr/bin/env python3
"""Generate src/GorillaDrive/Sheets.g.cs from design/sheets/*.json.
One struct/field per sheet row, built from that row's columns."""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
S = lambda n: json.load(open(root / "design/sheets" / f"{n}.json"))
q = lambda s: json.dumps(str(s))

out = ["// <auto-generated> from design/sheets by tools/gen_sheets.py. Edit the sheets, not this file.",
       "namespace GorillaDrive", "{"]

loc = S("locomotion")["rows"]
out.append("    /// <summary>Gorilla Tag movement rules (sheet: locomotion).</summary>")
out.append("    public static class LocomotionRules")
out.append("    {")
for r in loc:
    t = "int" if isinstance(r["value"], int) and not isinstance(r["value"], bool) else "float"
    v = f"{r['value']}" if t == "int" else f"{float(r['value'])}f"
    out.append(f"        /// <summary>{r['meaning']} ({r['unit']}). Source: {r['source']}.</summary>")
    out.append(f"        public const {t} {r['id']}Default = {v};")
out.append("        public static readonly (string id, float value, string meaning)[] All = {")
for r in loc:
    out.append(f"            ({q(r['id'])}, {float(r['value'])}f, {q(r['meaning'])}),")
out.append("        };")
out.append("    }")

out.append("    /// <summary>Desktop controls (sheet: controls).</summary>")
out.append("    public static class ControlRows")
out.append("    {")
out.append("        public static readonly (string id, string defaultKey, string action)[] All = {")
for r in S("controls")["rows"]:
    out.append(f"            ({q(r['id'])}, {q(r['default_key'])}, {q(r['action'])}),")
out.append("        };")
out.append("    }")

out.append("    /// <summary>Hooks into The Long Drive (sheet: tld_hooks).</summary>")
out.append("    public static class HookRows")
out.append("    {")
out.append("        public static readonly (string id, string howFound, string ifNotFound)[] All = {")
for r in S("tld_hooks")["rows"]:
    out.append(f"            ({q(r['id'])}, {q(r['how_found'])}, {q(r['if_not_found'])}),")
out.append("        };")
out.append("    }")

out.append("    /// <summary>Gorilla Tag content rows (sheet: gt_content).</summary>")
out.append("    public static class ContentRows")
out.append("    {")
out.append("        public static readonly (string id, string unityClass, string codeStruct)[] All = {")
for r in S("gt_content")["rows"]:
    out.append(f"            ({q(r['id'])}, {q(r['unity_class'])}, {q(r['code_struct'])}),")
out.append("        };")
out.append("    }")
out.append("}")
(root / "src/GorillaDrive/Sheets.g.cs").write_text("\n".join(out) + "\n")
print("wrote Sheets.g.cs")
