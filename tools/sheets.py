"""Preflight and code generation for the design sheets.

  python3 tools/sheets.py preflight   # list every empty cell and broken cross-sheet reference
  python3 tools/sheets.py generate    # preflight, then write Sheets.java from the rows
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHEETS = ROOT / 'sheets'
OUT = ROOT / 'mod/src/main/java/studcraft/gen/Sheets.java'
MIXINS = ROOT / 'mod/src/main/java/studcraft/mixin'

# column -> sheet whose ids it must name
REFS = {
    ('sky_faces', 'file'): 'roblox_files',
    ('asset_overrides', 'file'): 'roblox_files',
}
SHEET_NAMES = ['roblox_files', 'block_styles', 'sky_faces', 'asset_overrides', 'hooks', 'test_checks']


def load():
    return {n: json.loads((SHEETS / f'{n}.json').read_text()) for n in SHEET_NAMES}


def preflight(sheets, check_code=False):
    problems = []
    for name, sheet in sheets.items():
        ids = set()
        for i, row in enumerate(sheet['rows']):
            rid = row.get('id', f'#{i}')
            if rid in ids:
                problems.append(f'{name}.{rid}: duplicate id')
            ids.add(rid)
            for col in sheet['columns']:
                if col not in row or row[col] is None or (isinstance(row[col], str) and not row[col].strip()):
                    problems.append(f'{name}.{rid}.{col}: empty')
            for col in row:
                if col not in sheet['columns']:
                    problems.append(f'{name}.{rid}.{col}: not a column of the sheet')
    for (name, col), target in REFS.items():
        known = {r['id'] for r in sheets[target]['rows']}
        for row in sheets[name]['rows']:
            if row.get(col) not in known:
                problems.append(f"{name}.{row['id']}.{col}: '{row.get(col)}' is not a {target} id")
    for row in sheets['roblox_files']['rows']:
        users = {r[c] for (n, c), t in REFS.items() if t == 'roblox_files' for r in sheets[n]['rows']}
        if row['id'] not in users and row['used_by'] != 'block_styles':
            problems.append(f"roblox_files.{row['id']}: no sheet uses this file")
    for row in sheets['block_styles']['rows']:
        try:
            re.compile(row['match'])
        except re.error as e:
            problems.append(f"block_styles.{row['id']}.match: bad regex ({e})")
        if row['surface'] in ('studs', 'inlet') and row['studs_tile'] < 0:
            problems.append(f"block_styles.{row['id']}.studs_tile: {row['surface']} needs a tile")
    if check_code:
        for row in sheets['hooks']['rows']:
            if not (MIXINS / f"{row['mixin']}.java").exists():
                problems.append(f"hooks.{row['id']}.mixin: {row['mixin']}.java not written")
        mixins_json = json.loads((ROOT / 'mod/src/main/resources/studcraft.mixins.json').read_text())
        listed = set(mixins_json.get('client', []) + mixins_json.get('mixins', []))
        for row in sheets['hooks']['rows']:
            if row['mixin'] not in listed:
                problems.append(f"hooks.{row['id']}.mixin: not listed in studcraft.mixins.json")
    return problems


def jstr(s):
    return json.dumps(s)


def generate(sheets):
    L = []
    L.append('// Generated by tools/sheets.py from sheets/*.json. Edit the sheets, not this file.')
    L.append('package studcraft.gen;')
    L.append('')
    L.append('import java.util.List;')
    L.append('')
    L.append('public final class Sheets {')
    L.append('\tprivate Sheets() {}')
    L.append('')
    L.append('\tpublic record RobloxFile(String id, String path, String format, int width, int height) {}')
    L.append('\tpublic record BlockStyle(String id, String match, String requires, String surface, int studsTile, int outputSize, float colorMix, float saturation) {}')
    L.append('\tpublic record SkyFace(String id, String file, float[][] corners) {}')
    L.append('\tpublic record AssetOverride(String id, String target, String file, String transform, boolean listed) {}')
    L.append('')
    for row in sheets['roblox_files']['rows']:
        L.append(f"\tpublic static final RobloxFile FILE_{row['id'].upper()} = new RobloxFile({jstr(row['id'])}, {jstr(row['path'])}, {jstr(row['format'])}, {row['width']}, {row['height']});")
    L.append('\tpublic static final List<RobloxFile> FILES = List.of(' + ', '.join(f"FILE_{r['id'].upper()}" for r in sheets['roblox_files']['rows']) + ');')
    L.append('')
    L.append('\tpublic static final List<BlockStyle> BLOCK_STYLES = List.of(')
    rows = sheets['block_styles']['rows']
    for i, row in enumerate(rows):
        sep = ',' if i < len(rows) - 1 else ''
        L.append(f"\t\tnew BlockStyle({jstr(row['id'])}, {jstr(row['match'])}, {jstr(row['requires'])}, {jstr(row['surface'])}, {row['studs_tile']}, {row['output_size']}, {row['color_mix']}F, {row['saturation']}F){sep}")
    L.append('\t);')
    L.append('')
    L.append('\tpublic static final List<SkyFace> SKY_FACES = List.of(')
    rows = sheets['sky_faces']['rows']
    for i, row in enumerate(rows):
        sep = ',' if i < len(rows) - 1 else ''
        corners = ', '.join('{' + ', '.join(f'{v}F' for v in c) + '}' for c in row['corners'])
        L.append(f"\t\tnew SkyFace({jstr(row['id'])}, {jstr(row['file'])}, new float[][] {{{corners}}}){sep}")
    L.append('\t);')
    L.append('')
    L.append('\tpublic static final List<AssetOverride> ASSET_OVERRIDES = List.of(')
    rows = sheets['asset_overrides']['rows']
    for i, row in enumerate(rows):
        sep = ',' if i < len(rows) - 1 else ''
        L.append(f"\t\tnew AssetOverride({jstr(row['id'])}, {jstr(row['target'])}, {jstr(row['file'])}, {jstr(row['transform'])}, {str(row['listed']).lower()}){sep}")
    L.append('\t);')
    L.append('')
    L.append('\tpublic static final List<String> TEST_CHECKS = List.of(' + ', '.join(jstr(r['id']) for r in sheets['test_checks']['rows']) + ');')
    L.append('')
    L.append('\tpublic static RobloxFile file(String id) {')
    L.append('\t\tfor (RobloxFile f : FILES) if (f.id().equals(id)) return f;')
    L.append('\t\tthrow new IllegalArgumentException("No Roblox file row " + id);')
    L.append('\t}')
    L.append('}')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n')


if __name__ == '__main__':
    mode = sys.argv[1] if len(sys.argv) > 1 else 'preflight'
    sheets = load()
    problems = preflight(sheets, check_code=(mode == 'preflight-full'))
    total = sum(len(s['rows']) * len(s['columns']) for s in sheets.values())
    for p in problems:
        print('PREFLIGHT:', p)
    print(f'{total} cells checked across {len(sheets)} sheets, {len(problems)} problem(s)')
    if problems:
        sys.exit(1)
    if mode == 'generate':
        generate(sheets)
        print('wrote', OUT.relative_to(ROOT))
